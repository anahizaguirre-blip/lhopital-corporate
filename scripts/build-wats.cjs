const opentype = require('opentype.js');

const repo = path.join(__dirname, '..');
const fsrc = (p) => path.join(__dirname, '../node_modules/@fontsource', p);
const bodoni = opentype.loadSync(fsrc('bodoni-moda/files/bodoni-moda-latin-700-normal.woff'));
const jost = opentype.loadSync(fsrc('jost/files/jost-latin-400-normal.woff'));

const r = (n) => Math.round(n * 100) / 100;

// Path for a string centred on cx, with SVG-style letter-spacing between glyphs.
function textPath(font, str, cx, baseline, size, spacing = 0) {
  const glyphs = font.stringToGlyphs(str);
  const scale = size / font.unitsPerEm;
  const widths = glyphs.map((g) => g.advanceWidth * scale);
  const total = widths.reduce((a, b) => a + b, 0) + spacing * (glyphs.length - 1);
  let x = cx - total / 2;
  let d = '';
  glyphs.forEach((g, i) => {
    d += g.getPath(x, baseline, size).toPathData(2);
    x += widths[i] + spacing;
  });
  return { d, width: total };
}

