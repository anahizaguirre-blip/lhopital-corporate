// Extracts the outlined glyph paths from public/brand/wats-seal.svg (the WATS v3 seal,
// source: Cloudinary "wats_monogram_lhopital_v3_contornos") into src/lib/wats-paths.ts,
// so the hero can draw the seal inline and animate it.
// Usage: npm run build:assets
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const svg = fs.readFileSync(path.join(root, 'public/brand/wats-seal.svg'), 'utf8');

const ids = { W: 'W', A: 'A', T: 'T', S: 'S', tagline: 'we-are-the-standard', brand: 'lhopital' };
const paths = {};
for (const [key, id] of Object.entries(ids)) {
  const m = svg.match(new RegExp(`<path id="${id}"[^>]* d="([^"]+)"`));
  if (!m) throw new Error(`path #${id} not found in wats-seal.svg`);
  paths[key] = m[1].replace(/\s+/g, ' ').trim();
}

const ts =
  '// Generated by scripts/build-wats-paths.cjs from public/brand/wats-seal.svg. Do not edit by hand.\n' +
  'export const WATS_PATHS = ' + JSON.stringify(paths, null, 2) + ' as const;\n';
fs.writeFileSync(path.join(root, 'src/lib/wats-paths.ts'), ts);
console.log('wats-paths.ts:', Object.keys(paths).join(', '));
